from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, List, Optional

import numpy as np
import torch
from scipy.signal import savgol_filter
from torch import nn
from torch.nn import functional as F

from .enhancer_model import EnhancerDelayGRN


@dataclass
class EnhancerFit:
    model: EnhancerDelayGRN
    history: List[Dict[str, float]]


def _interpolate_observed(
    query_t: float, times: torch.Tensor, states: torch.Tensor
) -> torch.Tensor:
    q = torch.as_tensor(query_t, dtype=times.dtype, device=times.device)
    if q <= times[0]:
        return states[0]
    if q >= times[-1]:
        return states[-1]
    right = int(torch.searchsorted(times, q, right=False).item())
    left = max(0, right - 1)
    span = (times[right] - times[left]).clamp_min(1e-8)
    weight = (q - times[left]) / span
    return states[left] * (1.0 - weight) + states[right] * weight


def observed_lag_bank(
    model: EnhancerDelayGRN,
    t: float,
    times: torch.Tensor,
    states: torch.Tensor,
) -> torch.Tensor:
    return torch.stack(
        [
            _interpolate_observed(t - float(delay), times, states)
            for delay in model.delay_grid
        ]
    )


def _point_loss(
    predicted: torch.Tensor,
    target: torch.Tensor,
    kind: str,
    huber_beta: float,
    mask: Optional[torch.Tensor] = None,
) -> torch.Tensor:
    if mask is not None:
        mask = mask.to(dtype=torch.bool, device=predicted.device)
        predicted = predicted[mask]
        target = target[mask]
        if predicted.numel() == 0:
            return torch.zeros((), dtype=target.dtype, device=target.device)
    if kind == "mse":
        return torch.mean((predicted - target) ** 2)
    if kind == "huber":
        return F.smooth_l1_loss(
            predicted, target, beta=max(float(huber_beta), 1e-5)
        )
    raise ValueError("loss kind must be 'mse' or 'huber'")


def trajectory_derivative_loss(
    model: EnhancerDelayGRN,
    times: torch.Tensor,
    states: torch.Tensor,
    lag_banks: Optional[torch.Tensor] = None,
    true_derivative: Optional[torch.Tensor] = None,
    block_weights: tuple[float, float, float, float] = (0.35, 0.8, 0.8, 2.5),
    loss_kind: str = "huber",
    huber_beta: float = 0.08,
    intervention: Optional[dict] = None,
) -> tuple[torch.Tensor, Dict[str, torch.Tensor]]:
    if true_derivative is None:
        true_derivative = (states[1:] - states[:-1]) / (
            times[1:] - times[:-1]
        ).clamp_min(1e-5)[:, None]
    elif len(true_derivative) == len(states):
        true_derivative = true_derivative[:-1]
    if lag_banks is None:
        lag_banks = torch.stack(
            [
                observed_lag_bank(
                    model, float(times[i]), times[: i + 1], states[: i + 1]
                )
                for i in range(len(times) - 1)
            ]
        )
    pred_derivative = model.derivative_batch(
        times[:-1], states[:-1], lag_banks
    )["dy"]
    pa, pr, pe, px = model.split_state(pred_derivative)
    ta, tr, te, tx = model.split_state(true_derivative)
    access_mask = None
    tf_mask = None
    if intervention is not None:
        tf_index = int(intervention["tf_index"])
        start = float(intervention.get("start_time", 0.0))
        # The perturbed TF is externally clamped after the intervention.  Its
        # measured post-intervention derivative is therefore not generated by
        # the learned vector field and must not supervise TF/access dynamics.
        before = (times[:-1] < start)[:, None]
        access_mask = torch.ones_like(pa, dtype=torch.bool)
        tf_mask = torch.ones_like(pr, dtype=torch.bool)
        access_mask[:, tf_index : tf_index + 1] = before
        tf_mask[:, tf_index : tf_index + 1] = before
    losses = {
        "access": _point_loss(pa, ta, loss_kind, huber_beta, access_mask),
        "tf_rna": _point_loss(pr, tr, loss_kind, huber_beta, tf_mask),
        "enhancer": _point_loss(pe, te, loss_kind, huber_beta),
        "target": _point_loss(px, tx, loss_kind, huber_beta),
    }
    total = (
        block_weights[0] * losses["access"]
        + block_weights[1] * losses["tf_rna"]
        + block_weights[2] * losses["enhancer"]
        + block_weights[3] * losses["target"]
    )
    return total, losses


def _subsample_indices(n_times: int, n_points: int = 12) -> list[int]:
    stride = max(1, n_times // n_points)
    indices = list(range(0, n_times, stride))
    if indices[-1] != n_times - 1:
        indices.append(n_times - 1)
    return indices


def rollout_state_loss(
    model: EnhancerDelayGRN,
    item: dict,
    max_step: float = 0.05,
    method: str = "euler",
) -> torch.Tensor:
    indices = _subsample_indices(len(item["time"]), n_points=12)
    rollout_times = item["time"][indices]
    rollout_true = item["obs"][indices]
    rollout = model.integrate(
        rollout_times,
        item.get("initial_state", item["obs"][0]),
        max_step=max_step,
        intervention=item["intervention"],
        method=method,
    ).obs
    pa, pr, pe, px = model.split_state(rollout)
    ta, tr, te, tx = model.split_state(rollout_true)
    return (
        0.10 * torch.mean((pa - ta) ** 2)
        + 0.25 * torch.mean((pr - tr) ** 2)
        + 0.25 * torch.mean((pe - te) ** 2)
        + 1.40 * torch.mean((px - tx) ** 2)
    )


def response_delta_loss(
    model: EnhancerDelayGRN,
    control: dict,
    treated: dict,
    max_step: float = 0.05,
    method: str = "euler",
) -> torch.Tensor:
    """Supervise counterfactual response = treated − control."""

    indices = _subsample_indices(len(control["time"]), n_points=12)
    times = control["time"][indices]
    true_delta = treated["obs"][indices] - control["obs"][indices]
    model.set_reference_trajectory(control["time"], control["obs"])
    try:
        pred_control = model.integrate(
            times,
            control.get("initial_state", control["obs"][0]),
            max_step=max_step,
            method=method,
        ).obs
        pred_treated = model.integrate(
            times,
            treated.get("initial_state", treated["obs"][0]),
            max_step=max_step,
            intervention=treated["intervention"],
            method=method,
        ).obs
    finally:
        model.clear_reference()
    pred_delta = pred_treated - pred_control
    _, _, _, true_target = model.split_state(true_delta)
    _, _, _, pred_target = model.split_state(pred_delta)
    _, true_tf, _, _ = model.split_state(true_delta)
    _, pred_tf, _, _ = model.split_state(pred_delta)
    target_scale = true_target.std(dim=0).clamp_min(0.02)
    return (
        torch.mean(((pred_target - true_target) / target_scale) ** 2)
        + 0.15 * torch.mean((pred_tf - true_tf) ** 2)
    )


def response_derivative_loss(
    model: EnhancerDelayGRN,
    control: dict,
    treated: dict,
    huber_beta: float = 0.12,
) -> torch.Tensor:
    """Cheap teacher-forced loss on intervention-induced target derivatives.

    Taking treated-minus-control derivatives cancels common developmental
    forcing.  This directly identifies TF-dependent dynamic edges and delays,
    instead of allowing a large absolute-trajectory loss to drown out the
    comparatively small perturbation response.
    """

    if len(control["time"]) != len(treated["time"]):
        raise ValueError("control and treated trajectories must share a time grid")
    times = treated["time"][:-1]
    intervention = treated["intervention"] or {}
    start = float(intervention.get("start_time", 0.0))
    dt = float(torch.median(treated["time"][1:] - treated["time"][:-1]))
    mask = times >= start + max(0.02, 2.0 * dt)
    if int(mask.sum()) < 2:
        return torch.zeros((), dtype=times.dtype, device=times.device)

    pred_control = model.derivative_batch(
        times,
        control["obs"][:-1],
        control["lag_banks"],
    )["dy"]
    pred_treated = model.derivative_batch(
        times,
        treated["obs"][:-1],
        treated["lag_banks"],
    )["dy"]
    predicted_delta = pred_treated - pred_control
    true_delta = (
        treated["true_derivative"][:-1]
        - control["true_derivative"][:-1]
    )
    _, _, _, predicted_target = model.split_state(predicted_delta[mask])
    _, _, _, true_target = model.split_state(true_delta[mask])
    scale = true_target.std(dim=0).clamp_min(0.03)
    return F.smooth_l1_loss(
        predicted_target / scale,
        true_target / scale,
        beta=max(float(huber_beta), 1e-5),
    )


def _smooth_numpy(
    times: np.ndarray,
    observations: np.ndarray,
    window: int,
    polynomial: int,
) -> tuple[np.ndarray, np.ndarray]:
    times = np.asarray(times, dtype=np.float64)
    observations = np.asarray(observations, dtype=np.float64)
    if len(times) <= polynomial + 2:
        smooth = observations.copy()
        derivative = np.gradient(smooth, times, axis=0, edge_order=1)
        return smooth.astype(np.float32), derivative.astype(np.float32)
    chosen = min(int(window), len(times) if len(times) % 2 else len(times) - 1)
    if chosen % 2 == 0:
        chosen -= 1
    if chosen <= polynomial:
        smooth = observations.copy()
        derivative = np.gradient(smooth, times, axis=0, edge_order=1)
        return smooth.astype(np.float32), derivative.astype(np.float32)
    dt = float(np.median(np.diff(times)))
    smooth = savgol_filter(
        observations, chosen, polynomial, axis=0, mode="interp"
    )
    derivative = savgol_filter(
        observations,
        chosen,
        polynomial,
        deriv=1,
        delta=dt,
        axis=0,
        mode="interp",
    )
    return smooth.astype(np.float32), derivative.astype(np.float32)


def _cyclic_subset(items: list[dict], epoch: int, size: int) -> list[dict]:
    if size <= 0 or size >= len(items):
        return items
    start = ((epoch - 1) * size) % len(items)
    return [items[(start + offset) % len(items)] for offset in range(size)]


def fit_enhancer_model(
    model: EnhancerDelayGRN,
    trajectories: Iterable[dict],
    epochs: int = 1200,
    lr: float = 2.5e-2,
    weight_decay: float = 1e-5,
    edge_l1: float = 0.0,
    edge_group_l1: float = 2.0e-3,
    dynamic_l2: float = 1.5e-4,
    target_forcing_l2: float = 3.0e-3,
    delay_entropy: float = 2.0e-4,
    access_delay_anchor: Optional[torch.Tensor | np.ndarray] = None,
    target_delay_anchor: Optional[torch.Tensor | np.ndarray] = None,
    access_delay_anchor_weight: float = 0.0,
    target_delay_anchor_weight: float = 0.04,
    delay_lr_scale: float = 0.25,
    response_derivative_weight: float = 0.55,
    rollout_weight: float = 0.30,
    response_weight: float = 0.45,
    rollout_start_epoch: int = 15,
    response_start_epoch: int = 25,
    rollout_every: int = 3,
    aux_trajectory_batch: int = 5,
    aux_response_batch: int = 4,
    smooth_derivatives: bool = True,
    smooth_window: int = 9,
    smooth_polynomial: int = 3,
    derivative_loss_kind: str = "huber",
    patience: int = 180,
    seed: int = 13,
    device: Optional[torch.device] = None,
) -> EnhancerFit:
    np.random.seed(seed)
    torch.manual_seed(seed)
    device = device or torch.device(
        "cuda" if torch.cuda.is_available() else "cpu"
    )
    model = model.to(device)
    model.clear_reference()

    prepared = []
    for index, item in enumerate(trajectories):
        times_np = np.asarray(item["time"], dtype=np.float32)
        observations_np = np.asarray(item["obs"], dtype=np.float32)
        if smooth_derivatives:
            smoothed_np, derivative_np = _smooth_numpy(
                times_np,
                observations_np,
                smooth_window,
                smooth_polynomial,
            )
        else:
            smoothed_np = observations_np
            derivative_np = np.gradient(
                observations_np, times_np, axis=0, edge_order=1
            ).astype(np.float32)
        prepared.append(
            {
                "name": item.get("name", f"traj_{index}"),
                "time": torch.as_tensor(
                    times_np, dtype=torch.float32, device=device
                ),
                "obs": torch.as_tensor(
                    smoothed_np, dtype=torch.float32, device=device
                ),
                "raw_obs": torch.as_tensor(
                    observations_np, dtype=torch.float32, device=device
                ),
                "true_derivative": torch.as_tensor(
                    derivative_np, dtype=torch.float32, device=device
                ),
                "intervention": item.get("intervention"),
                "initial_state": torch.as_tensor(
                    item.get("initial_state", observations_np[0]),
                    dtype=torch.float32,
                    device=device,
                ),
            }
        )
    if not prepared:
        raise ValueError("At least one trajectory is required")

    for item in prepared:
        item["lag_banks"] = torch.stack(
            [
                observed_lag_bank(
                    model,
                    float(item["time"][i]),
                    item["time"][: i + 1],
                    item["obs"][: i + 1],
                )
                for i in range(len(item["time"]) - 1)
            ]
        )

    control_items = [item for item in prepared if item["intervention"] is None]
    treated_items = [
        item for item in prepared if item["intervention"] is not None
    ]
    primary_control = control_items[0] if control_items else prepared[0]

    delay_parameters = []
    if model.delay_parameterization == "continuous":
        delay_parameters.extend(
            [model.raw_access_delay, model.raw_target_delay]
        )
    else:
        delay_parameters.extend(
            [model.access_delay_logits, model.target_delay_logits]
        )
    delay_parameters = [
        parameter for parameter in delay_parameters if parameter.requires_grad
    ]
    delay_ids = {id(parameter) for parameter in delay_parameters}
    main_parameters = [
        parameter
        for parameter in model.parameters()
        if parameter.requires_grad and id(parameter) not in delay_ids
    ]
    parameter_groups = [
        {
            "params": main_parameters,
            "lr": lr,
            "weight_decay": weight_decay,
        }
    ]
    if delay_parameters:
        parameter_groups.append(
            {
                "params": delay_parameters,
                "lr": lr * delay_lr_scale,
                "weight_decay": 0.0,
            }
        )
    optimizer = torch.optim.AdamW(parameter_groups)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=max(1, epochs), eta_min=lr * 0.04
    )

    def anchor_tensor(value, expected_shape):
        if value is None:
            return None
        tensor = torch.as_tensor(value, dtype=torch.float32, device=device)
        if tuple(tensor.shape) != tuple(expected_shape):
            raise ValueError(
                "delay anchor has shape "
                f"{tuple(tensor.shape)}, expected {tuple(expected_shape)}"
            )
        return tensor

    access_anchor = anchor_tensor(
        access_delay_anchor, (model.n_tfs,)
    )
    target_anchor = anchor_tensor(
        target_delay_anchor, (model.n_targets, model.n_tfs)
    )

    history: List[Dict[str, float]] = []
    best = float("inf")
    best_state = None
    stale = 0
    n_trajectories = max(1, len(prepared))

    for epoch in range(1, epochs + 1):
        optimizer.zero_grad(set_to_none=True)
        total = torch.zeros((), device=device)
        block_totals = {
            "access": 0.0,
            "tf_rna": 0.0,
            "enhancer": 0.0,
            "target": 0.0,
        }
        for item in prepared:
            loss, blocks = trajectory_derivative_loss(
                model,
                item["time"],
                item["obs"],
                item["lag_banks"],
                true_derivative=item["true_derivative"],
                loss_kind=derivative_loss_kind,
                intervention=item["intervention"],
            )
            total = total + loss
            for key in block_totals:
                block_totals[key] += float(blocks[key].detach())
        total = total / n_trajectories

        active_base = model.edge_base * model.pathway_prior
        if edge_l1 > 0.0:
            total = total + edge_l1 * torch.mean(torch.abs(active_base))
        group_square = active_base**2
        if model.dynamic_edges:
            prior = model.pathway_prior.unsqueeze(0)
            group_square = group_square + torch.sum(
                (model.edge_time_sin * prior) ** 2
                + (model.edge_time_cos * prior) ** 2,
                dim=0,
            )
        total = total + edge_group_l1 * torch.mean(
            torch.sqrt(group_square + 1e-8)
        )

        if model.dynamic_edges and model.n_time_freqs > 0:
            frequency_weights = torch.arange(
                1,
                model.n_time_freqs + 1,
                dtype=model.edge_time_sin.dtype,
                device=device,
            ).square()[:, None, None]
            total = total + dynamic_l2 * torch.mean(
                frequency_weights
                * (model.edge_time_sin**2 + model.edge_time_cos**2)
            )
        if model.target_forcing.shape[1] > 1:
            total = total + target_forcing_l2 * torch.mean(
                model.target_forcing[:, 1:] ** 2
            )
        access_prob, target_prob = model.delay_probabilities()
        if model.delay_parameterization == "softmax":
            entropy = -(
                torch.mean(
                    torch.sum(
                        access_prob * torch.log(access_prob + 1e-8), dim=-1
                    )
                )
                + torch.mean(
                    torch.sum(
                        target_prob * torch.log(target_prob + 1e-8), dim=-1
                    )
                )
            )
            entropy_scale = delay_entropy * max(
                0.15, 1.0 - epoch / max(1, epochs)
            )
            total = total + entropy_scale * entropy
        else:
            entropy = torch.zeros((), device=device)

        learned_delays = model.get_delays()
        normalizer = max(model.max_tau, 0.05) ** 2
        anchor_loss = torch.zeros((), device=device)
        if access_anchor is not None and access_delay_anchor_weight > 0.0:
            anchor_loss = anchor_loss + access_delay_anchor_weight * torch.mean(
                (learned_delays["access_to_tf"] - access_anchor) ** 2
            ) / normalizer
        if target_anchor is not None and target_delay_anchor_weight > 0.0:
            active_mask = model.pathway_prior > 0
            anchor_loss = anchor_loss + target_delay_anchor_weight * torch.mean(
                (
                    learned_delays["tf_to_target"][active_mask]
                    - target_anchor[active_mask]
                )
                ** 2
            ) / normalizer
        total = total + anchor_loss

        response_derivative = torch.zeros((), device=device)
        if response_derivative_weight > 0.0 and treated_items:
            for treated in treated_items:
                response_derivative = response_derivative + response_derivative_loss(
                    model, primary_control, treated
                )
            response_derivative = response_derivative / len(treated_items)
            total = total + response_derivative_weight * response_derivative

        rollout_loss = torch.zeros((), device=device)
        response_loss = torch.zeros((), device=device)
        aux_epoch = (
            epoch % max(1, rollout_every) == 0
            and (
                (rollout_weight > 0 and epoch >= rollout_start_epoch)
                or (response_weight > 0 and epoch >= response_start_epoch)
            )
        )
        max_step = 0.08 if epoch < epochs * 0.50 else 0.04
        if aux_epoch:
            if rollout_weight > 0 and epoch >= rollout_start_epoch:
                rollout_items = _cyclic_subset(
                    prepared, epoch, aux_trajectory_batch
                )
                for item in rollout_items:
                    rollout_loss = rollout_loss + rollout_state_loss(
                        model, item, max_step=max_step, method="euler"
                    )
                rollout_loss = rollout_loss / max(1, len(rollout_items))
                ramp = min(
                    1.0, (epoch - rollout_start_epoch + 1) / 30.0
                )
                total = total + (rollout_weight * ramp) * rollout_loss
            if (
                response_weight > 0
                and epoch >= response_start_epoch
                and treated_items
            ):
                response_items = _cyclic_subset(
                    treated_items, epoch, aux_response_batch
                )
                for treated in response_items:
                    response_loss = response_loss + response_delta_loss(
                        model,
                        primary_control,
                        treated,
                        max_step=max_step,
                        method="euler",
                    )
                response_loss = response_loss / max(1, len(response_items))
                ramp = min(
                    1.0, (epoch - response_start_epoch + 1) / 30.0
                )
                total = total + (response_weight * ramp) * response_loss

        if not torch.isfinite(total):
            raise RuntimeError(f"Non-finite training loss at epoch {epoch}")
        total.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        optimizer.step()
        # The unused duplicate-intercept column is kept exactly at zero after
        # the gradient update so it cannot create checkpoint noise.
        with torch.no_grad():
            model.target_forcing[:, 0].zero_()
        scheduler.step()

        value = float(total.detach())
        row = {
            "epoch": float(epoch),
            "loss": value,
            "delay_entropy": float(entropy.detach()),
            "delay_anchor": float(anchor_loss.detach()),
            "response_derivative": float(response_derivative.detach()),
            "rollout": float(rollout_loss.detach()),
            "response": float(response_loss.detach()),
            "lr": float(optimizer.param_groups[0]["lr"]),
            "delay_lr": float(
                optimizer.param_groups[1]["lr"]
                if len(optimizer.param_groups) > 1
                else 0.0
            ),
        }
        row.update(
            {
                f"derivative_{key}": value_sum / n_trajectories
                for key, value_sum in block_totals.items()
            }
        )
        history.append(row)

        eligible_checkpoint = (
            rollout_weight <= 0 and response_weight <= 0
        ) or aux_epoch
        if eligible_checkpoint and value < best - 1e-7:
            best = value
            best_state = {
                key: tensor.detach().cpu().clone()
                for key, tensor in model.state_dict().items()
            }
            stale = 0
        elif eligible_checkpoint:
            stale += 1
            if stale >= patience:
                break

    if best_state is None:
        best_state = {
            key: tensor.detach().cpu().clone()
            for key, tensor in model.state_dict().items()
        }
    model.load_state_dict(best_state)
    model.clear_reference()
    return EnhancerFit(model=model, history=history)
